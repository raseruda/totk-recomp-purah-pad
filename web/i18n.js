  let currentRomfs = "USen";
  let currentLang = "en";

  function setLang(romfsCode) {
    const code = String(romfsCode || "USen");
    currentRomfs = code;
    currentLang = ROMFS_TO_UI[code] || (code.toLowerCase().startsWith("pt") ? "pt" : "en");
    document.documentElement.lang = currentLang === "pt" ? "pt-BR" : currentLang;
    document.title = t("docTitle");
  }

  function t(key, vars) {
    const d = DICT[currentLang] || DICT.en;
    let str = (d && Object.prototype.hasOwnProperty.call(d, key) ? d[key] : undefined);
    if (str === undefined) {
      str = Object.prototype.hasOwnProperty.call(DICT.en, key) ? DICT.en[key] : key;
    }
    if (vars && typeof str === "string") {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replaceAll(`{${k}}`, String(v));
      }
    }
    return str;
  }

  function applyDom() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
  }

  return {
    setLang,
    getLang: () => currentLang,
    getRomfsCode: () => currentRomfs,
    t,
    applyDom,
  };
